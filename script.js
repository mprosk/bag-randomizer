function getSwatchHeight() {
  return swatchesElement.getBoundingClientRect().height;
}

function getMaximumSwatchHeight() {
  return Math.max(minimumSwatchHeight, window.innerHeight / 2);
}

function setSwatchHeight(height) {
  const nextHeight = Math.min(getMaximumSwatchHeight(), Math.max(minimumSwatchHeight, height));
  document.documentElement.style.setProperty("--swatch-height", `${nextHeight}px`);
  swatchResizer.setAttribute("aria-valuenow", String(Math.round(nextHeight)));
}

swatchResizer.addEventListener("pointerdown", (event) => {
  dragStartY = event.clientY;
  dragStartHeight = getSwatchHeight();
  swatchResizer.classList.add("is-dragging");
  swatchResizer.setPointerCapture(event.pointerId);
});

swatchResizer.addEventListener("pointermove", (event) => {
  if (!swatchResizer.hasPointerCapture(event.pointerId)) return;
  setSwatchHeight(dragStartHeight + dragStartY - event.clientY);
});

function endResize(event) {
  if (swatchResizer.hasPointerCapture(event.pointerId)) {
    swatchResizer.releasePointerCapture(event.pointerId);
  }
  swatchResizer.classList.remove("is-dragging");
}

swatchResizer.addEventListener("pointerup", endResize);
swatchResizer.addEventListener("pointercancel", endResize);
swatchResizer.addEventListener("dblclick", () => {
  document.documentElement.style.removeProperty("--swatch-height");
  swatchResizer.setAttribute("aria-valuenow", String(Math.round(getSwatchHeight())));
});

swatchResizer.addEventListener("keydown", (event) => {
  const height = getSwatchHeight();
  const changesHeight = ["ArrowUp", "ArrowDown", "Home", "End"].includes(event.key);
  if (!changesHeight) return;

  event.preventDefault();
  if (event.key === "ArrowUp") setSwatchHeight(height + 12);
  if (event.key === "ArrowDown") setSwatchHeight(height - 12);
  if (event.key === "Home") setSwatchHeight(minimumSwatchHeight);
  if (event.key === "End") setSwatchHeight(getMaximumSwatchHeight());
});

swatchResizer.setAttribute("aria-valuemax", String(Math.round(getMaximumSwatchHeight())));
swatchResizer.setAttribute("aria-valuenow", String(Math.round(getSwatchHeight())));
window.addEventListener("resize", () => {
  swatchResizer.setAttribute("aria-valuemax", String(Math.round(getMaximumSwatchHeight())));
  if (document.documentElement.style.getPropertyValue("--swatch-height")) {
    setSwatchHeight(getSwatchHeight());
  } else {
    swatchResizer.setAttribute("aria-valuenow", String(Math.round(getSwatchHeight())));
  }
});
